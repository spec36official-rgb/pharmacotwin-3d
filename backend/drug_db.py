def _generate_pocket_pdb_block(
    receptor_name: str,
    pdb_id: str,
    ligand_res: str,
    ligand_atoms: List[tuple],
    pocket_residues: List[tuple],
) -> str:
    """
    Generate a clean, standards-compliant PDB coordinate block containing the receptor
    active-site pocket residues (Chain A) and co-folded drug ligand atoms (HETATM Chain L)
    so 3Dmol.js renders instantaneous, zero-latency interactive 3D structures with
    exact inter-atomic distance measurements (Angstroms).
    """
    lines = [
        f"HEADER    PHARMACOTWIN-3D CO-FOLDED COMPLEX ({pdb_id}) - {receptor_name}",
        f"TITLE     ALPHAFOLD-3 / PDB POCKET COMPLEX FOR {ligand_res}",
    ]
    serial = 1
    # Receptor pocket alpha-helix / beta-sheet / sidechain atoms (Chain A)
    for res_name, res_seq, atoms in pocket_residues:
        for atom_name, elem, x, y, z in atoms:
            lines.append(
                f"ATOM  {serial:5d} {atom_name:<4s} {res_name:>3s} A{res_seq:4d}    "
                f"{x:8.3f}{y:8.3f}{z:8.3f}  1.00 92.40          {elem:>2s}"
            )
            serial += 1
    lines.append("TER")
    # Ligand HETATM records (Chain L)
    for atom_name, elem, x, y, z in ligand_atoms:
        lines.append(
            f"HETATM{serial:5d} {atom_name:<4s} {ligand_res:>3s} L 901    "
            f"{x:8.3f}{y:8.3f}{z:8.3f}  1.00 89.80          {elem:>2s}"
        )
        serial += 1
    lines.append("END")
    return "\n".join(lines)


